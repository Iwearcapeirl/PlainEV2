def family_of(make: str, model: str):
    for mk, rx, fam, title in RULES:
        if mk == make and re.search(rx, model):
            return fam, title
    return None


if __name__ == "__main__":
    cars = json.load(open(sys.argv[1]))
    missing = [f"{c['Make']} | {c['Model']}" for c in cars if not family_of(c["Make"], c["Model"])]
    titles = sorted({family_of(c["Make"], c["Model"])[1] for c in cars if family_of(c["Make"], c["Model"])})
    fams = {family_of(c["Make"], c["Model"])[0] for c in cars if family_of(c["Make"], c["Model"])}
    print("unmapped:", missing)
    print(len(fams), "families,", len(titles), "distinct Wikipedia titles")
    json.dump(titles, open(sys.argv[2], "w"), ensure_ascii=False, indent=0)
